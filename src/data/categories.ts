/**
 * Режимге жараша категориянын темаларын кайтарат.
 * «Терең изилдөө» режиминде категория өз темаларын толугу менен берет,
 * үстүнө аналитикалык researchTopics кошулат. deep-research — өзүнчө категория.
 */
export function topicsFor(category: Category, mode: 'quick' | 'research'): Topic[] {
  if (mode === 'quick' || category.mode === 'research') return category.topics;
  return [...category.topics, ...(category.researchTopics ?? [])];
}

/** Режимде көрсөтүлүүчү категориялар. */
export function categoriesFor(mode: 'quick' | 'research'): Category[] {
  if (mode === 'quick') return categories.filter((c) => c.mode !== 'research');
  return categories.filter(
    (c) => c.mode === 'research' || (c.researchTopics?.length ?? 0) > 0,
  );
}
